// Test helper for the Supabase pack's selftests (not a selftest itself): a
// scratch git repo laid out as an install would be — .ssdd/hooks/ holds the
// hooks, .ssdd/packs/supabase/ this pack — so the real prod-guard loads the
// real pack. Works from the source tree (hooks in ../../mechanisms/hooks) and
// from an installed repo (hooks in ../../hooks).
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readdirSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const PACK_DIR = dirname(fileURLToPath(import.meta.url));
export const HOOKS_DIR = [join(PACK_DIR, '..', '..', 'hooks'), join(PACK_DIR, '..', '..', 'mechanisms', 'hooks')]
  .find((d) => existsSync(join(d, 'prod-guard.mjs')));
const NODE = process.execPath;

// An example proof frame: the source project's check-migration helper's.
export const EXAMPLE_FRAME = {
  prologue: [
    '-- Pre-merge proof (generated by check-migration.mjs --proof). Runs on PRODUCTION via',
    '-- `supabase db query --linked` and ROLLS BACK. Timeouts bound the locks the DDL takes.',
    'BEGIN;',
    "SET LOCAL lock_timeout = '3s';",
    "SET LOCAL statement_timeout = '30s';",
    "SET LOCAL idle_in_transaction_session_timeout = '10s';",
  ],
  epilogue: [
    'DO $proof_tripwire$ BEGIN',
    "  IF current_setting('lock_timeout') <> '3s' OR current_setting('statement_timeout') <> '30s'",
    "     OR current_setting('idle_in_transaction_session_timeout') <> '10s' THEN",
    "    RAISE EXCEPTION 'proof timeouts were changed inside the proof — aborted';",
    '  END IF;',
    'END $proof_tripwire$;',
    'ROLLBACK;',
  ],
};
export const proofOf = (body) => [...EXAMPLE_FRAME.prologue, body.trim(), ';', ...EXAMPLE_FRAME.epilogue, ''].join('\n');

const copyDir = (from, to) => {
  mkdirSync(to, { recursive: true });
  for (const f of readdirSync(from)) if (f.endsWith('.mjs') && !f.includes('.selftest.')) copyFileSync(join(from, f), join(to, f));
};

// → { repo, tmp, file(name, text), claude, cursor, claudeMcp, cursorMcp, cleanup }.
// Each runner returns { decision: 'allow'|'ask'|'deny', reason, status, out }.
export function makeLayout({ config } = {}) {
  const repo = realpathSync(mkdtempSync(join(tmpdir(), 'ssdd-supabase-pack-')));
  spawnSync('git', ['-C', repo, 'init', '-q']);
  copyDir(HOOKS_DIR, join(repo, '.ssdd', 'hooks'));
  copyDir(PACK_DIR, join(repo, '.ssdd', 'packs', 'supabase'));
  if (config) writeFileSync(join(repo, '.ssdd', 'config.json'), JSON.stringify(config));
  const tmp = join(repo, 'tmp');
  mkdirSync(tmp);
  const hook = join(repo, '.ssdd', 'hooks', 'prod-guard.mjs');
  const run = (payload, env = {}, cwd = repo) => {
    const r = spawnSync(NODE, [hook], {
      input: JSON.stringify(payload), cwd, encoding: 'utf8',
      env: { ...process.env, CLAUDE_PROJECT_DIR: '', SSDD_PROJECT_DIR: '', ...env },
    });
    let out = null;
    try { out = r.stdout.trim() ? JSON.parse(r.stdout) : null; } catch { out = { unparsable: r.stdout }; }
    let decision = 'allow';
    let reason = '';
    if (r.status !== 0) decision = `exit ${r.status}: ${r.stderr}`;
    else if (out?.hookSpecificOutput) ({ permissionDecision: decision, permissionDecisionReason: reason } = out.hookSpecificOutput);
    else if (out?.permission) { decision = out.permission; reason = out.agent_message ?? ''; }
    return { decision, reason, status: r.status, out };
  };
  return {
    repo,
    tmp,
    file(name, text) { const p = join(tmp, name); mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, text); return p; },
    claude: (command, { cwd = repo } = {}) =>
      run({ hook_event_name: 'PreToolUse', tool_name: 'Bash', tool_input: { command }, cwd }, { CLAUDE_PROJECT_DIR: repo }, cwd),
    cursor: (command, { cwd = repo } = {}) => run({ hook_event_name: 'beforeShellExecution', command, cwd, workspace_roots: [repo] }, {}, cwd),
    claudeMcp: (tool, input = {}) =>
      run({ hook_event_name: 'PreToolUse', tool_name: tool, tool_input: input, cwd: repo }, { CLAUDE_PROJECT_DIR: repo }),
    cursorMcp: (tool, input, server = 'supabase', url = '') =>
      run({ hook_event_name: 'beforeMCPExecution', tool_name: tool, tool_input: input, mcp_server_name: server, url, workspace_roots: [repo] }),
    cleanup: () => rmSync(repo, { recursive: true, force: true }),
  };
}

// Under both harnesses: Claude Code's verdict, and Cursor's (an ask is a deny there).
export function both(layout, command, opts) {
  const c = layout.claude(command, opts);
  const k = layout.cursor(command, opts);
  return { claude: c, cursor: k };
}
