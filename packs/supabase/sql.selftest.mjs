describe("Part 4's changes", () => {
  it('a static read passes without READ ONLY', () => {
    for (const sql of [
      'select 1',
      "select count(*) from pg_policies; select has_table_privilege('a','public.users','DELETE');",
      'BEGIN; SELECT 1; ROLLBACK;',
      'BEGIN READ ONLY;\nselect 1;\nCOMMIT;\n',
    ]) assert.deepEqual(classifySql(sql, {}), { verdict: 'read', rule: 'static read' }, sql);
  });

  it('a READ ONLY transaction keeps its rule name', () => {
    assert.deepEqual(classifySql(RO('select 1;'), {}), { verdict: 'read', rule: 'read-only transaction' });
  });

  it('lookups the corpus uses', () => {
    for (const sql of [
      "select to_regprocedure('public.f(text)') is null",
      "select to_regclass('public.t')",
      'select (aclexplode(relacl)).privilege_type from pg_class',
      'select enum_range(null::t)',
      'select round(sqrt(power(2, 2)) * radians(sin(1) + cos(1) + asin(0)))',
    ]) assert.equal(classifySql(sql, {}).verdict, 'read', sql);
  });

  it('pure functions the corpora use (Task 10)', () => {
    for (const sql of [
      'select percentile_cont(0.5) within group (order by x), percentile_disc(0.9) within group (order by x) from t',
      "select jsonb_array_elements_text(j), jsonb_array_elements(j) from t",
      "select regexp_matches(s, 'a(b)')",
      'select vector_dims(embedding) from articles limit 1',
    ]) assert.equal(classifySql(sql, {}).verdict, 'read', sql);
  });

  it('EXPLAIN options and ORDER BY / GROUP BY / PARTITION BY (…) are not calls', () => {
    for (const sql of [
      'EXPLAIN (COSTS OFF) SELECT id FROM t',
      'select a from t order by (a + 1)',
      'select a, count(*) from t group by (a)',
      'select row_number() over (partition by (a) order by (b)) from t',
    ]) assert.equal(classifySql(sql, {}).verdict, 'read', sql);
    assert.notEqual(classifySql('select by(1)', {}).verdict, 'read');
    assert.notEqual(classifySql('select x from t where explain(1)', {}).verdict, 'read');
  });

  it('writes are named', () => {
    assert.deepEqual(classifySql('BEGIN; INSERT INTO t VALUES (1); COMMIT;', {}), { verdict: 'writes', rule: 'INSERT statement' });
    const probe = classifySql('BEGIN; ALTER POLICY p ON t TO authenticated; UPDATE t SET a = 1; ROLLBACK;', {});
    assert.equal(probe.verdict, 'writes');
    assert.match(probe.rule, /^rolled back ALTER statement/);
    assert.equal(classifySql('truncate table t', {}).verdict, 'writes');
    assert.deepEqual(classifySql('with d as (delete from t returning *) select * from d', {}), { verdict: 'writes', rule: 'WITH … DELETE statement' });
    assert.deepEqual(classifySql('insert into t values (1)', {}), { verdict: 'writes', rule: 'INSERT statement' });
  });

  it('unclear, with the rule', () => {
    assert.deepEqual(classifySql("SELECT current_setting('client_encoding')", {}), { verdict: 'unclear', rule: 'names client_encoding' });
    assert.deepEqual(classifySql('select public.f()', {}), { verdict: 'unclear', rule: 'calls public.f' });
    assert.deepEqual(classifySql('select f(1)', {}), { verdict: 'unclear', rule: 'calls f' });
    assert.equal(classifySql("select set_config('a','b',true)", {}).verdict, 'unclear');
    assert.deepEqual(classifySql('SET search_path = x; select 1', {}), { verdict: 'unclear', rule: 'SET statement' });
    assert.deepEqual(classifySql('select 1 /* x', {}), { verdict: 'unclear', rule: 'unterminated block comment' });
    assert.deepEqual(classifySql('  ', {}), { verdict: 'unclear', rule: 'no statements' });
  });

  it('a proof without a configured frame is unclear', () => {
    assert.deepEqual(classifySql(REAL_PROOF, {}), { verdict: 'unclear', rule: 'proof frame not configured' });
  });

  it('live extensions come from the options', () => {
    const p = proof('CREATE EXTENSION IF NOT EXISTS pg_net;', 'SELECT true AS ok;');
    assert.equal(classifySql(p, { proofFrame: FRAME, liveExtensions: ['pg_net'] }).verdict, 'proof');
    assert.notEqual(classifySql(p, { proofFrame: FRAME }).verdict, 'proof');
  });

  it('personalReads', () => {
    const personalReads = { tables: ['auth.users'], columns: ['phone'] };
    assert.deepEqual(classifySql('select email, phone from auth.users', { personalReads }),
      { verdict: 'read', rule: 'static read', personal: ['auth.users', 'phone'] });
    assert.deepEqual(classifySql('select count(*) from public.matches', { personalReads }), { verdict: 'read', rule: 'static read' });
    assert.deepEqual(classifySql("select 'phone' as k", { personalReads }), { verdict: 'read', rule: 'static read' });
    assert.deepEqual(classifySql('select "Phone", x from "auth"."users"', { personalReads: { tables: ['auth.users'] } }).personal, ['auth.users']);
    assert.deepEqual(classifySql('select users.id from users', { personalReads: { tables: ['users'] } }).personal, ['users']);
  });

  it('statementKinds', () => {
    assert.deepEqual(statementKinds('BEGIN READ ONLY; select 1; with x as (select 1) select * from x; ROLLBACK;'),
      ['BEGIN READ ONLY', 'SELECT', 'WITH', 'ROLLBACK']);
    assert.deepEqual(statementKinds("insert into t values ('a;b'); -- x;\ndelete from t"), ['INSERT', 'DELETE']);
  });

  it('never throws', () => {
    for (const sql of [null, undefined, 3, '', ';;;', "'", '$$', 'select (', ')))']) {
      assert.doesNotThrow(() => classifySql(sql, {}), String(sql));
      assert.doesNotThrow(() => statementKinds(sql), String(sql));
    }
  });
});
