// Tests for the Supabase pack's SQL classifier. Ported from the source
// project's two supabase-guard suites (reads, rolled-back proofs, and every
// out-of-band / write shape), as unit tests on classifySql, plus Part 4's
// changes: static reads, named writes, reasons, config-driven proofs and
// extensions, personalReads.
// Run: node --test packs/supabase/sql.selftest.mjs
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { classifySql, statementKinds } from './sql-readonly.mjs';

// A proof frame like the source project's check-migration helper writes. The
// frame is project config (productionGuard.supabase.proofFrame); these lines
// are the source project's, used as a realistic example.
const PROLOGUE = [
  '-- Pre-merge proof (generated by check-migration.mjs --proof). Runs on PRODUCTION via',
  '-- `supabase db query --linked` and ROLLS BACK. Timeouts bound the locks the DDL takes.',
  'BEGIN;',
  "SET LOCAL lock_timeout = '3s';",
  "SET LOCAL statement_timeout = '30s';",
  "SET LOCAL idle_in_transaction_session_timeout = '10s';",
];
const EPILOGUE = [
  'DO $proof_tripwire$ BEGIN',
  "  IF current_setting('lock_timeout') <> '3s' OR current_setting('statement_timeout') <> '30s'",
  "     OR current_setting('idle_in_transaction_session_timeout') <> '10s' THEN",
  "    RAISE EXCEPTION 'proof timeouts were changed inside the proof — aborted';",
  '  END IF;',
  'END $proof_tripwire$;',
  'ROLLBACK;',
];
const FRAME = { prologue: PROLOGUE, epilogue: EPILOGUE };
const LIVE = ['pg_net', 'pg_cron', 'pgcrypto', 'uuid-ossp', 'vector', 'supabase_vault', 'pg_stat_statements'];
const OPTS = { proofFrame: FRAME, liveExtensions: LIVE };
const proof = (migration, assertions) => [
  ...PROLOGUE, '-- ── migration: m.sql', migration.trim(), ';', '-- ── assertions: a.sql', assertions.trim(), ';', ...EPILOGUE, '',
].join('\n');
const HEADER = PROLOGUE[0] + '\n';
const AFTER_PROLOGUE = "SET LOCAL idle_in_transaction_session_timeout = '10s';\n";
const forged = (sql) => proof('SELECT 1;', 'SELECT true AS ok;').replace(AFTER_PROLOGUE, AFTER_PROLOGUE + sql + '\n');
const RO = (body) => `BEGIN READ ONLY;\n${body}\nROLLBACK;\n`;
const passes = (sql, opts = OPTS) => ['read', 'proof'].includes(classifySql(sql, opts).verdict);

const REAL_PROOF = proof(
  "CREATE OR REPLACE FUNCTION public.f() RETURNS trigger LANGUAGE plpgsql AS $function$\n" +
  "BEGIN\n  IF TG_OP = 'INSERT' THEN NEW.x := 1; END IF;\n  RETURN NEW;\nEND;\n$function$;\n" +
  'CREATE TRIGGER tr BEFORE INSERT ON public.t FOR EACH ROW EXECUTE FUNCTION public.f();\n' +
  'DO $x$ BEGIN PERFORM 1; COMMIT; END $x$;\n',
  ";\nSET LOCAL ROLE authenticated;\nINSERT INTO t (a) VALUES ('it''s; COMMIT; --');\nRESET ROLE;\n" +
  "DO $$ BEGIN DELETE FROM t; PERFORM set_config('step1.del', 'ran', true); EXCEPTION WHEN insufficient_privilege THEN NULL; END $$;\n" +
  "SELECT (SELECT count(*) = 0 FROM pg_policies WHERE cmd = 'DELETE') AS ok;\n",
);

describe('reads and proofs that pass (ported)', () => {
  for (const [name, sql] of [
    ['read-only catalog read', RO("select count(*) from pg_policies where tablename = 'users';\nselect has_table_privilege('authenticated','public.users','DELETE');")],
    ['START TRANSACTION … READ ONLY', 'start transaction isolation level serializable, read only; select 1; rollback;'],
    ['comments + E-string + dollar body', RO("-- note: delete\n/* nested /* update */ */ select E'it\\'s', $q$ drop $q$;")],
    ['window + filter after `)`', RO('select count(*) filter (where x > 1), row_number() over (partition by y) from t;')],
    ['regex with backslashes in a plain string', RO("select count(*) from public.device_tokens where token !~ '^ExponentPushToken\\[[^]]+\\]$';")],
    ['trailing backslash in a plain string', RO("select 'a\\'; select 1;")],
    ['string literals naming out-of-band functions', RO("select count(*) from pg_proc where proname like 'dblink%' or prosrc ~* 'pg_notify|pg_terminate_backend|http_get';")],
    ["`AS '` inside a string is data", RO("select 'x' as a, 'y AS ''z''' as b, 'cast as ' as c;")],
    ['pg_net queue table', RO('select count(*) from net.http_request_queue;')],
    ['COPY / PROGRAM / lo_ words inside strings', RO("select 'COPY t TO PROGRAM lo_import' as note;")],
  ]) it(name, () => assert.equal(classifySql(sql, OPTS).verdict, 'read', name));

  it('the helper-built proof', () => assert.deepEqual(classifySql(REAL_PROOF, OPTS), { verdict: 'proof', rule: 'proof frame' }));

  const NET_MIGRATION = 'CREATE OR REPLACE FUNCTION public.fire() RETURNS void LANGUAGE plpgsql SECURITY DEFINER\n' +
    "SET search_path TO 'public' AS $function$\nBEGIN\n  PERFORM net.http_post(url := 'https://x.test/fn', body := '{}'::jsonb);\nEND;\n$function$;\n";
  const COUNT_QUEUE = 'SELECT (SELECT count(*) FROM net.http_request_queue) >= 0 AS ok;\n';
  for (const [name, sql] of [
    ['net.http_post inside a function body + queue counting', proof(NET_MIGRATION, COUNT_QUEUE)],
    ['quoted "net"."http_post" call', proof('SELECT 1;', "SELECT \"net\".\"http_post\"(url := 'https://x.test') IS NOT NULL AS ok;")],
    ['backslash regex CHECK constraint', proof("ALTER TABLE public.device_tokens ADD CONSTRAINT device_tokens_token_format\n  CHECK (token ~ '^Expo(nent)?PushToken\\[[^]]+\\]$');", 'SELECT true AS ok;')],
    ['out-of-band names only inside plain strings', proof('SELECT 1;', "SELECT 'dblink_exec pg_terminate_backend http_get(' <> '' AS ok;")],
    ['spaced qualifier `net . http_get(`', proof('SELECT 1;', "SELECT net . http_get(url := 'https://x.test') IS NOT NULL AS ok;")],
    ['CREATE EXTENSION of a live extension', proof('CREATE EXTENSION IF NOT EXISTS pg_net;\nCREATE EXTENSION IF NOT EXISTS "uuid-ossp";', COUNT_QUEUE)],
    ["enum migration + a `LIKE 'dblink%'` assertion", proof("CREATE TYPE public.k AS ENUM ('a', 'b');", "SELECT count(*) >= 0 AS ok FROM pg_proc WHERE proname LIKE 'dblink%';")],
  ]) it(`proof: ${name}`, () => assert.equal(classifySql(sql, OPTS).verdict, 'proof', name));
});

